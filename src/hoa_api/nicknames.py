"""课程昵称 → 官方课程名映射。

学生和 Agent 常用的口语/缩写与课程官方名往往不一致，例如「高数」对应
「微积分」、「线性代数」对应「代数」。检索时先用原词匹配，匹配不到再用
本表回落到官方名。

与老 course-server 的昵称表保持一致，保证切流前后检索结果相同。
"""

from __future__ import annotations

NICKNAMES: dict[str, str] = {
    "自动化导论": "自动化专业导论",
    "高级语言程序设计": "计算机思维与实践",
    "程序设计": "计算机思维与实践",
    "计算机导论": "计算机专业导论",
    "大英": "大学英语",
    "英语": "大学英语",
    "习特": "习近平新时代中国特色社会主义思想概论",
    "思道": "思想道德与法治",
    "线性代数": "代数",
    "线代": "代数",
    "代几": "代数",
    "高数": "微积分",
    "高等数学": "微积分",
    "大物": "大学物理",
    "三合一": "电路与电子学",
    "软构": "软件构造",
    "计网": "计算机网络",
    "系统": "操作系统",
}


def resolve_nickname(keyword: str) -> str:
    """把昵称还原成官方课程名；没有对应关系时原样返回。"""
    key = (keyword or "").strip()
    if not key:
        return key
    return NICKNAMES.get(key, key)
